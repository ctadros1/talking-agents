"""Vendor a small, licensed Lucide SVG sprite from its pinned npm package.

Run once with Python's standard library. Normal builds need no network or npm.
"""

from __future__ import annotations

import hashlib
import io
import json
import tarfile
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSION = "1.70.0"
ICONS = (
    "arrow-down-right",
    "arrow-left",
    "arrow-right",
    "arrow-up-right",
    "download",
    "external-link",
    "play",
    "pause",
    "rotate-ccw",
    "step-forward",
    "step-back",
    "skip-forward",
    "volume-2",
    "volume-x",
    "rotate-3d",
    "house",
    "music-2",
    "box",
    "move",
    "zoom-in",
    "zoom-out",
)


def main():
    url = f"https://registry.npmjs.org/lucide-static/-/lucide-static-{VERSION}.tgz"
    payload = urllib.request.urlopen(url).read()
    nodes = {}
    symbols = []
    with tarfile.open(fileobj=io.BytesIO(payload), mode="r:gz") as archive:
        (ROOT / "web/lucide.LICENSE").write_bytes(archive.extractfile("package/LICENSE").read())
        for name in ICONS:
            raw = archive.extractfile(f"package/icons/{name}.svg").read()
            svg = ET.fromstring(raw)
            parts = []
            nodes[name] = []
            for child in svg:
                tag = child.tag.split("}")[-1]
                child.tag = tag
                parts.append(ET.tostring(child, encoding="unicode"))
                nodes[name].append([tag, child.attrib])
            symbols.append(f'<symbol id="{name}" viewBox="0 0 24 24">' + "".join(parts) + "</symbol>")
    (ROOT / "web/icons.svg").write_text(
        f"<!-- Lucide {VERSION}, ISC; see lucide.LICENSE -->\n"
        '<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" '
        'stroke-width="2" stroke-linecap="round" stroke-linejoin="round">' + "".join(symbols) + "</svg>\n"
    )
    (ROOT / "web/icon-nodes.mjs").write_text(
        f"// Lucide {VERSION}, ISC; see lucide.LICENSE. Generated by scripts/vendor_icons.py.\n"
        "export const iconNodes = " + json.dumps(nodes, separators=(",", ":")) + ";\n"
    )
    (ROOT / "web/icons-source.json").write_text(
        json.dumps(
            {
                "library": "Lucide Static",
                "version": VERSION,
                "source": url,
                "package_sha256": hashlib.sha256(payload).hexdigest(),
                "license": "ISC",
                "icons": ICONS,
            },
            indent=2,
        )
        + "\n"
    )
    print(f"Vendored {len(ICONS)} Lucide icons with license and source digest.")


if __name__ == "__main__":
    main()
